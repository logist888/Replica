#!/usr/bin/env python3
"""tokens.json -> tokens.css + tailwind.preset.js. Источник правды: tokens.json."""
import json, pathlib
here = pathlib.Path(__file__).parent
t = json.loads((here / "tokens.json").read_text(encoding="utf-8"))

css = ["/* generated by gen_tokens.py from tokens.json, do not edit */", ":root {"]
for k, v in t["color"].items():
    css.append(f"  --color-{k}: {v};")
for k, v in t["font"].items():
    if not k.startswith("_"):
        css.append(f"  --font-{k}: {v};")
for k, v in t["type"].items():
    css += [f"  --text-{k}-size: {v['size']}px;", f"  --text-{k}-line: {v['line']}px;", f"  --text-{k}-weight: {v['weight']};"]
for i, v in enumerate(t["space"]):
    css.append(f"  --space-{i}: {v}px;")
for k, v in t["radius"].items():
    css.append(f"  --radius-{k}: {v}px;")
for k, v in t["shadow"].items():
    css.append(f"  --shadow-{k}: {v};")
for k, v in t["motion"].items():
    if not k.startswith("_"):
        css.append(f"  --motion-{k}: {v};")
for k, v in t["layout"].items():
    if isinstance(v, int):
        css.append(f"  --layout-{k}: {v}px;")
css += ["}", "", "@media (prefers-reduced-motion: reduce) {",
        "  :root { --motion-fast: 0ms; --motion-base: 0ms; }", "}", ""]
(here / "tokens.css").write_text("\n".join(css), encoding="utf-8")

colors = {k: f"var(--color-{k})" for k in t["color"]}
preset = {
    "theme": {
        "extend": {
            "colors": colors,
            "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
            "fontSize": {k: [f"{v['size']}px", {"lineHeight": f"{v['line']}px", "fontWeight": str(v["weight"])}] for k, v in t["type"].items()},
            "borderRadius": {k: f"{v}px" for k, v in t["radius"].items()},
            "boxShadow": {k: f"var(--shadow-{k})" for k in t["shadow"]},
            "maxWidth": {"test": f"{t['layout']['test-max-width']}px", "page": f"{t['layout']['page-max-width']}px"},
            "minHeight": {"touch": f"{t['layout']['min-touch-target']}px"},
            "minWidth": {"touch": f"{t['layout']['min-touch-target']}px"},
        }
    }
}
(here / "tailwind.preset.js").write_text(
    "// generated by gen_tokens.py, do not edit\nmodule.exports = " + json.dumps(preset, indent=2, ensure_ascii=False) + ";\n",
    encoding="utf-8")
(here / "tokens.js").write_text("window.TOKENS = " + json.dumps(t, ensure_ascii=False) + ";\n", encoding="utf-8")
print("ok")
